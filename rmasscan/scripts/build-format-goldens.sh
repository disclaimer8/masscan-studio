#!/usr/bin/env bash
# Capture C-oracle goldens for the rmasscan output formats through `--readscan`
# (offline parity, docs/superpowers/specs/2026-11-06-rmasscan-output-formats-design.md §6.1).
#
#   build-format-goldens.sh --oracle BIN --inputs DIR --out DIR
#
# BIN is the pinned C masscan (built by build-oracle.sh); DIR holds the `-oB` inputs written by
# `cargo run -p rmasscan-cli --example format_inputs -- DIR`. Writes into --out: manifest.json,
# services.txt, protocols.txt and outputs/<case>.out. Runs on the oracle host (Linux, sudo, getent, jq).
#
# SAFETY: masscan only converts files here (`--readscan`, no scan), and every invocation still runs
# inside a fresh network namespace (`sudo -n unshare -n`, only a DOWN loopback exists).
#
# Every case runs twice; the two runs must agree after masking the fields C takes from the clock
# when it writes them (XML `start`, `finished time/timestr/elapsed`, grepable `# Masscan done at`).
# Outputs of inputs larger than STORE_MAX are hashed but not stored (their input is regenerated by
# the test from the same example code).
set -euo pipefail
export LC_ALL=C

PIN=8e6b3b0c07a81e8ea61d557c06134a21a6881614
PIN_SHA256=8afc8ec81f2e051389116908b01a4482b42e020bc48254585b7dcca4b25e2a3e
STORE_MAX=$((64 * 1024))

die() { echo "FATAL: $*" >&2; exit 2; }
usage() { echo "usage: $0 --oracle BIN --inputs DIR --out DIR" >&2; exit 2; }

ORACLE='' INPUTS='' OUT=''
while [ $# -gt 0 ]; do
  case $1 in
    --oracle) [ $# -ge 2 ] || usage; ORACLE=$2; shift 2 ;;
    --inputs) [ $# -ge 2 ] || usage; INPUTS=$2; shift 2 ;;
    --out) [ $# -ge 2 ] || usage; OUT=$2; shift 2 ;;
    *) usage ;;
  esac
done
[ -n "$ORACLE" ] && [ -n "$INPUTS" ] && [ -n "$OUT" ] || usage
for t in sha256sum getent jq od sed grep stat cmp ip sudo unshare; do
  command -v "$t" >/dev/null || die "'$t' not found"
done
[ -x "$ORACLE" ] || die "oracle $ORACLE is not executable"
[ -d "$INPUTS" ] || die "inputs $INPUTS is not a directory"
INPUTS=$(cd "$INPUTS" && pwd)
mkdir -p "$OUT"
OUT=$(cd "$OUT" && pwd)

# ---- oracle pin ------------------------------------------------------------
# binary_sha256 is the build of $PIN recorded in tests/golden/manifest.json.
sha=$(sha256sum <"$ORACLE" | cut -d' ' -f1)
[ "$sha" = "$PIN_SHA256" ] || die "oracle sha256 $sha != $PIN_SHA256"

# ---- network isolation (as build-oracle.sh) --------------------------------
NS=(sudo -n unshare -n)
"${NS[@]}" true 2>/dev/null || die "cannot create a network namespace; refusing to run masscan"
ns_links=$("${NS[@]}" ip -o link) || die "'ip -o link' failed inside namespace"
[ -n "$ns_links" ] || die "namespace interface list is empty"
echo "$ns_links" | grep -q ': lo:' || die "namespace has no lo"
[ "$(echo "$ns_links" | grep -vc ': lo:' || true)" = "0" ] || die "namespace has interfaces besides lo"
echo "[*] isolation: sudo unshare -n"

# `--readscan` skips /etc/masscan/masscan.conf (main.c:1627, `!is_readscan`); refuse it anyway, so no
# host configuration can ever reach a fixture.
if "${NS[@]}" test -e /etc/masscan/masscan.conf; then
  die "/etc/masscan/masscan.conf exists"
fi
ORACLE_VERSION=$("${NS[@]}" "$ORACLE" --version 2>&1 | grep -i 'version' | head -1 | sed 's/^Masscan version //; s/ *(.*$//' || true)
[ "$ORACLE_VERSION" = "1.3.9-integration" ] || die "unexpected version string '$ORACLE_VERSION'"
echo "[*] oracle $PIN_SHA256 ($ORACLE_VERSION)"

STAGE=$(mktemp -d "${TMPDIR:-/tmp}/rmasscan-out.XXXXXX")
trap 'rm -rf "$STAGE"' EXIT
rm -rf "$OUT/outputs"
mkdir -p "$OUT/outputs"
: >"$STAGE/cases.jsonl"
: >"$STAGE/inputs.jsonl"

# ---- masks -----------------------------------------------------------------
# mask_args KIND... : sed -E expressions; tests/formats_golden.rs applies the same rules.
mask_args() {
  local k
  for k in "$@"; do
    case $k in
      xml_start) printf '%s\n' '-e' 's/^(<nmaprun scanner="masscan" start=")[0-9]+"/\1*"/' ;;
      xml_finished) printf '%s\n' '-e' 's/^(<finished time=")[0-9]+(" timestr=")[^"]*(" elapsed=")[0-9]+"/\1*\2*\3*"/' ;;
      grepable_done) printf '%s\n' '-e' 's/^(# Masscan done at ).*$/\1*/' ;;
      *) die "unknown mask $k" ;;
    esac
  done
}
# mask_line_re KIND : the line a mask must hit exactly once
mask_line_re() {
  case $1 in
    xml_start) echo '^<nmaprun scanner="masscan" start="[0-9]+"' ;;
    xml_finished) echo '^<finished time="[0-9]+" timestr="[^"]*" elapsed="[0-9]+"' ;;
    grepable_done) echo '^# Masscan done at ' ;;
  esac
}
# masked FILE KIND... : the file with the masks applied, on stdout
masked() {
  local f=$1; shift
  if [ $# -eq 0 ]; then cat "$f"; return; fi
  local e=()
  mapfile -t e < <(mask_args "$@")
  sed -E "${e[@]}" "$f"
}

# ---- inputs ----------------------------------------------------------------
# records_ports FILE : "ip_proto port" of the 15-byte status records (type 6/7, length 13; out-binary.c:154-211).
# The bytes are regrouped by 15 in awk, whatever line width od prints (uutils od does not keep `-w15` lines on
# large inputs).
records_ports() {
  local f=$1 size n
  size=$(stat -c %s "$f")
  n=$(( (size - 198) / 15 ))
  [ "$n" -gt 0 ] || return 0
  od -An -v -tu1 -j99 -N$((n * 15)) "$f" |
    awk '{ for (k = 1; k <= NF; k++) { v[c++] = $k; if (c == 15) {
             if ((v[0] == 6 || v[0] == 7) && v[1] == 13) print v[10], v[11] * 256 + v[12]; c = 0 } } }'
}

declare -A STORED
ports_all="$STAGE/ports"
: >"$ports_all"
shopt -s nullglob
inputs=("$INPUTS"/*.scan.bin)
[ ${#inputs[@]} -gt 0 ] || die "no *.scan.bin in $INPUTS"
for f in "${inputs[@]}"; do
  name=${f##*/}
  size=$(stat -c %s "$f")
  head -c 11 "$f" | cmp -s - <(printf 'masscan/1.1') || die "$name: not a masscan -oB file"
  [ $(( (size - 198) % 15 )) -eq 0 ] || die "$name: not 99 + 15*n + 99 bytes"
  if [ "$size" -le "$STORE_MAX" ]; then STORED[$name]=true; else STORED[$name]=false; fi
  records_ports "$f" >>"$ports_all"
  jq -n -c --arg name "$name" --arg sha "$(sha256sum <"$f" | cut -d' ' -f1)" \
    --argjson size "$size" --argjson records $(( (size - 198) / 15 )) --argjson stored "${STORED[$name]}" \
    '{name: $name, sha256: $sha, size_bytes: $size, records: $records, stored: $stored}' >>"$STAGE/inputs.jsonl"
  echo "[*] input $name: $size bytes, stored=${STORED[$name]}"
done
[ -n "${STORED[basic.scan.bin]:-}" ] || die "basic.scan.bin is required (filter cases)"

# ---- services and protocols ------------------------------------------------
# What getservbyport(port, "tcp") answers for TCP records and getservbyport(port, "udp") for UDP records on this
# host (out-tcp-services.c:34-99), in /etc/services form: TCP ports first, then UDP ports, each in port order.
: >"$OUT/services.txt"
for proto_name in 6:tcp 17:udp; do
  num=${proto_name%%:*} name=${proto_name#*:}
  for p in $(awk -v n="$num" '$1 == n { print $2 }' "$ports_all" | sort -n -u); do
    getent services "$p/$name" >>"$OUT/services.txt" || true   # exit 2: no entry, C prints `unknown`
  done
done
echo "[*] services.txt: $(wc -l <"$OUT/services.txt") entries"
# What getprotobynumber answers for every other ip_proto of the records (oproto_service_name,
# out-tcp-services.c:101-118: -oG names an ICMP or SCTP record's service by its protocol), in /etc/protocols form.
: >"$OUT/protocols.txt"
for n in $(awk '$1 != 6 && $1 != 17 { print $1 }' "$ports_all" | sort -n -u); do
  getent protocols "$n" >>"$OUT/protocols.txt" || true   # exit 2: no entry, C prints `unknown`
done
echo "[*] protocols.txt: $(wc -l <"$OUT/protocols.txt") entries"

# ---- cases -----------------------------------------------------------------
# run_case NAME INPUT KIND ARGS... : ARGS use @INPUT@ and @OUTPUT@ for the two paths. KIND (xml,
# grepable, other) selects the masks when the output is not empty.
run_case() {
  local name=$1 input=$2 kind=$3; shift 3
  local in_path="$INPUTS/$input" r a rc
  for r in 1 2; do
    local out_path="$STAGE/run$r/$name.out"
    mkdir -p "$STAGE/run$r"
    local argv=()
    for a in "$@"; do
      a=${a//@INPUT@/"$in_path"}
      argv+=("${a//@OUTPUT@/"$out_path"}")
    done
    rc=0
    "${NS[@]}" "$ORACLE" "${argv[@]}" >"$STAGE/run$r/$name.stdout" 2>"$STAGE/run$r/$name.stderr" || rc=$?
    [ "$rc" = 0 ] || { cat "$STAGE/run$r/$name.stderr" >&2; die "$name: exit $rc"; }
    [ -f "$out_path" ] || die "$name: no output file"
  done
  local o1="$STAGE/run1/$name.out" o2="$STAGE/run2/$name.out"
  local masks=()
  if [ -s "$o1" ]; then
    case $kind in
      xml) masks=(xml_start xml_finished) ;;
      grepable) masks=(grepable_done) ;;
    esac
  fi
  local m hits
  for m in "${masks[@]}"; do
    for o in "$o1" "$o2"; do
      hits=$(grep -cE "$(mask_line_re "$m")" "$o" || true)
      [ "$hits" = 1 ] || die "$name: mask $m hits $hits lines"
    done
  done
  local h1 h2
  h1=$(masked "$o1" "${masks[@]}" | sha256sum | cut -d' ' -f1)
  h2=$(masked "$o2" "${masks[@]}" | sha256sum | cut -d' ' -f1)
  [ "$h1" = "$h2" ] || die "$name: the two runs differ after masking"
  cmp -s "$STAGE/run1/$name.stdout" "$STAGE/run2/$name.stdout" || die "$name: stdout differs between runs"
  cmp -s "$STAGE/run1/$name.stderr" "$STAGE/run2/$name.stderr" || die "$name: stderr differs between runs"

  local size rel=null
  size=$(stat -c %s "$o1")
  if [ "${STORED[$input]}" = true ]; then
    cp "$o1" "$OUT/outputs/$name.out"
    rel="\"outputs/$name.out\""
  fi
  local args_json masks_json
  args_json=$(printf '%s\n' "$@" | jq -R . | jq -s -c .)
  masks_json=$(printf '%s\n' "${masks[@]}" | jq -R 'select(length > 0) | {kind: .}' | jq -s -c .)
  jq -n -c --arg name "$name" --arg input "$input" --argjson args "$args_json" --argjson output "$rel" \
    --arg sha "$(sha256sum <"$o1" | cut -d' ' -f1)" --arg msha "$h1" --argjson size "$size" \
    --argjson masks "$masks_json" --arg in_path "$in_path" --arg out_path "$o1" \
    --rawfile stdout "$STAGE/run1/$name.stdout" --rawfile stderr "$STAGE/run1/$name.stderr" \
    '{name: $name, input: $input, args: $args, output: $output, sha256: $sha, masked_sha256: $msha,
      size_bytes: $size, masks: $masks,
      stdout: ($stdout | split($in_path) | join("@INPUT@")),
      stderr: ($stderr | split($in_path) | join("@INPUT@") | split($out_path) | join("@OUTPUT@"))}' \
    >>"$STAGE/cases.jsonl"
  echo "[+] $name: $size bytes, masks=${masks[*]:-none}"
}

FORMATS=(list:-oL:other json:-oJ:other ndjson:-oD:other grepable:-oG:grepable xml:-oX:xml
  binary:-oB:other hostonly:-oH:other unicornscan:-oU:other)
for f in "${inputs[@]}"; do
  input=${f##*/}
  stem=${input%.scan.bin}
  for show in open open-closed; do
    show_args=()
    [ "$show" = open ] || show_args=(--show open,closed)
    for spec in "${FORMATS[@]}"; do
      IFS=: read -r fmt flag kind <<<"$spec"
      run_case "$stem.$show.$fmt" "$input" "$kind" --readscan @INPUT@ "$flag" @OUTPUT@ "${show_args[@]}"
    done
    run_case "$stem.$show.xml-webxml" "$input" xml --readscan @INPUT@ -oX @OUTPUT@ --webxml "${show_args[@]}"
  done
done
# Targets and ports before --readscan filter the records (in-binary.c parse_status2): C takes every
# following argument without a leading '-' as a file (main-conf.c:3266-3278, main.c:1764).
run_case filter.open.list basic.scan.bin other --range 10.0.0.0/31 -p80 --readscan @INPUT@ -oL @OUTPUT@
run_case filter.open.grepable basic.scan.bin grepable --range 10.0.0.0/31 -p80 --readscan @INPUT@ -oG @OUTPUT@
# Non-TCP records: an address filter only. A `-p` filter is not captured: C compares the record's unshifted port
# with the shifted ranges (in-filter.c:14-17), rmasscan compares (ip_proto, port) (design 2026-11-08 protocols Р5).
if [ -n "${STORED[protocols.scan.bin]:-}" ]; then
  run_case filter.protocols.list protocols.scan.bin other --range 192.0.2.0/28 --readscan @INPUT@ -oL @OUTPUT@
  run_case filter.protocols.grepable protocols.scan.bin grepable --range 192.0.2.0/28 --readscan @INPUT@ -oG @OUTPUT@
fi

# ---- manifest --------------------------------------------------------------
# Subshell: os-release defines VERSION too.
HOST="$(. /etc/os-release && echo "${PRETTY_NAME:-unknown}"), kernel $(uname -r), $(uname -m)"
jq -n --arg pin "$PIN" --arg sha "$PIN_SHA256" --arg version "$ORACLE_VERSION" \
  --arg at "$(date -u +%Y-%m-%dT%H:%M:%SZ)" --arg host "$HOST" \
  --slurpfile inputs "$STAGE/inputs.jsonl" --slurpfile cases "$STAGE/cases.jsonl" \
  '{oracle: {git_head: $pin, binary_sha256: $sha, version: $version}, captured_at: $at, host: $host,
    isolation: "sudo unshare -n",
    services_source: "getent services <port>/tcp (TCP records) and <port>/udp (UDP records) on the oracle host",
    protocols_source: "getent protocols <ip_proto> on the oracle host for the records that are neither TCP nor UDP",
    store_max_bytes: '"$STORE_MAX"', inputs: $inputs, cases: $cases}' >"$OUT/manifest.json"
echo "[*] done: $(jq '.cases | length' "$OUT/manifest.json") cases in $OUT"
