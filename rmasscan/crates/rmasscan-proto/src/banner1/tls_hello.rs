//! Строители ClientHello (`src/proto-ssl.c:1076-1254`, `src/vulncheck-heartbleed.c`, `src/vulncheck-sslv3.c`,
//! справка 4c §A2). Шаблоны — константы байт в байт как C, сверены с дампом оракула
//! `tests/golden/tcp-banners/tls-hellos.out`, а не переписаны из исходников.
//!
//! Динамизация `ssl_hello()` (время и SipHash-отпечаток в поле random) применяется у C только к трём шаблонам
//! режимов проверок (`src/stack-tcp-core.c:542,558,578`); обычный hello и hello второго соединения уходят на
//! провод статичными байтами шаблона, включая запечённый random (справка §A2, §G п. 3).

use rmasscan_core::cookie::siphash24;

/// Какой из пяти ClientHello строить. `Default` — первое соединение на TLS-порт, `Tls13` — второе
/// (`banner_ssl_12`, `next` первого потока), остальные три — hello режимов `--heartbleed`, `--ticketbleed` и
/// `--vuln poodle|sslv3` (справка §E3). Потребитель — таблица потоков задачи 5; до неё только тесты.
// Потребитель — задача 5 подэтапа 4c.
#[allow(dead_code)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TlsHelloKind {
    Default,
    Tls13,
    Heartbeat,
    Ticketbleed,
    Sslv3Poodle,
}

/// ClientHello вида `kind` на момент `now_secs` (секунды Unix, как `time(0)` в `ssl_hello`). Для
/// `Default`/`Tls13` момент не используется: байты шаблона как есть.
#[allow(dead_code)]
pub(crate) fn tls_hello(kind: TlsHelloKind, now_secs: u64) -> Vec<u8> {
    match kind {
        TlsHelloKind::Default => HELLO_DEFAULT.to_vec(),
        TlsHelloKind::Tls13 => HELLO_TLS13.to_vec(),
        TlsHelloKind::Heartbeat => dynamicize(HELLO_HEARTBEAT, now_secs),
        TlsHelloKind::Ticketbleed => dynamicize(HELLO_TICKETBLEED, now_secs),
        TlsHelloKind::Sslv3Poodle => add_fallback_scsv(dynamicize(HELLO_SSLV3, now_secs)),
    }
}

/// `ssl_hello(templ)` (`src/proto-ssl.c:1224-1254`): копия шаблона, байты 11..15 — `now` big-endian
/// (`unsigned`, то есть младшие 32 бита), байты 15..43 — младший байт `siphash24` от `(i + now)` как u32 LE
/// с ключом {0, 0} для i в 4..32. Длина берётся из поля записи шаблона, как `ssl_hello_size` (`:1211-1220`);
/// у наших констант она равна длине среза.
fn dynamicize(template: &[u8], now_secs: u64) -> Vec<u8> {
    let now = now_secs as u32;
    let mut px = template.to_vec();
    if let Some(t) = px.get_mut(11..15) {
        t.copy_from_slice(&now.to_be_bytes());
    }
    for i in 4u32..32 {
        let val = i.wrapping_add(now);
        let c = siphash24(&val.to_le_bytes(), 0, 0) as u8;
        if let Some(b) = px.get_mut(11 + i as usize) {
            *b = c;
        }
    }
    px
}

/// `ssl_add_cipherspec(px, 0x5600, 1)` для SSLv3-шаблона (`src/proto-ssl.c:1123-1206`): `TLS_FALLBACK_SCSV`
/// в конец списка шифров и +2 в три поля длины (список шифров, рукопожатие, запись). Список шифров ищется как
/// у C: байт длины session id на смещении 43. Всё, что не похоже на ClientHello SSLv3, C возвращает без
/// изменений с `internal error` в stderr; здесь такая же тихая отдача входа (вызывается только на нашем
/// шаблоне).
fn add_fallback_scsv(mut px: Vec<u8>) -> Vec<u8> {
    let Some(&sid_len) = px.get(43) else {
        return px;
    };
    if px.first() != Some(&0x16) || px.get(1..3) != Some(&[0x03, 0x00][..]) {
        return px;
    }
    let offset = 44 + usize::from(sid_len);
    let Some(len2_bytes) = px.get(offset..offset + 2) else {
        return px;
    };
    let len2 = usize::from(u16::from_be_bytes([len2_bytes[0], len2_bytes[1]]));
    let insert_at = offset + 2 + len2;
    if insert_at > px.len() {
        return px;
    }
    px.splice(insert_at..insert_at, [0x56, 0x00]);
    let bump16 = |px: &mut [u8], at: usize| {
        if let Some(f) = px.get_mut(at..at + 2) {
            let v = u16::from_be_bytes([f[0], f[1]]).wrapping_add(2);
            f.copy_from_slice(&v.to_be_bytes());
        }
    };
    bump16(&mut px, offset);
    if let Some(f) = px.get_mut(6..9) {
        let v = (u32::from(f[0]) << 16 | u32::from(f[1]) << 8 | u32::from(f[2])) + 2;
        f.copy_from_slice(&[(v >> 16) as u8, (v >> 8) as u8, v as u8]);
    }
    bump16(&mut px, 3);
    px
}
