//! Шов между CLI и ОС (AGPL-3.0). В этой задаче он минимален: источники
//! энтропии и времени для политики seed и порта источника живого скана.
//! Расширяется методами обнаружения и открытия адаптера в задаче 5.

/// Всё, что `run` берёт у ОС. Тесты подставляют fake; настоящая реализация
/// (`OsBackend`) живёт только в бинарнике под `#[cfg(not(test))]`.
pub trait Backend {
    /// 64 бита энтропии ОС (seed живого скана).
    fn entropy64(&self) -> u64;
    /// Секунды Unix-времени (порт источника по умолчанию).
    fn unix_time(&self) -> u64;
}
